const TYPE_EN = { 1: "Metropolitan City", 2: "Sub-Metropolitan City", 3: "Municipality", 4: "Rural Municipality" };
const TYPE_NE = { 1: "महानगरपालिका", 2: "उपमहानगरपालिका", 3: "नगरपालिका", 4: "गाउँपालिका" };

// Form ma save hune value English (jastai "Bhaktapur Municipality"), nameNe chai dekhauna matra
export const nepalLocations = RAW.map(([province, provinceNe, districts]) => ({
  province,
  provinceNe,
  districts: districts.map(([name, nameNe, municipalities]) => ({
    name,
    nameNe,
    municipalities: municipalities.map(([en, ne, type, wardCount]) => ({
      name: `${en} ${TYPE_EN[type]}`,
      nameNe: `${ne} ${TYPE_NE[type]}`,
      type,
      wards: Array.from({ length: wardCount }, (_, i) => i + 1),
    })),
  })),
}));

// Saved English value lai bhasha anusar dekhaune (napaye jasto chha testai)
export const localizePlace = ({ province, district, municipality } = {}, isEn = false) => {
  if (isEn) return { province, district, municipality };

  const prov = nepalLocations.find((item) => item.province === province);
  const dist = prov?.districts.find((item) => item.name === district);
  const muni = dist?.municipalities.find((item) => item.name === municipality);

  return {
    province: prov?.provinceNe || province,
    district: dist?.nameNe || district,
    municipality: muni?.nameNe || municipality,
  };
};
